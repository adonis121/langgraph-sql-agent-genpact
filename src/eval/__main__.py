"""Run the eval set against the real model: python -m src.eval

For each question: run the reference SQL, run the agent (traced), compare the agent's final
step result with the reference result. Prints the score and writes docs/eval-report.md.
"""
import os
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from dotenv import load_dotenv

from src.agent.graph import build_graph
from src.agent.llm import get_llm
from src.agent.prompts import format_rows_as_table
from src.agent.state import initial_state
from src.config import REPO_ROOT, load_settings
from src.db.database import connect_readonly, run_query
from src.eval.compare import compare_results
from src.eval.questions import QUESTIONS, EvalQuestion
from src.tracing import run_traced

REPORT_PATH = REPO_ROOT / "docs" / "eval-report.md"
ROWS_IN_REPORT = 10


@dataclass
class Outcome:
    item: EvalQuestion
    passed: bool
    reason: str
    state: dict
    trace_path: Path


def no_reply(question: str) -> str:
    # The eval is not interactive: a clarification gets an empty reply, ends in decline,
    # and counts as a fail.
    return ""


def evaluate(item: EvalQuestion, graph, engine, model: str) -> Outcome:
    reference = run_query(engine, item.sql).rows
    state, _, trace_path = run_traced(graph, initial_state(item.question), model=model,
                                      ask_user=no_reply)
    if state["status"] != "done" or not state["results"]:
        return Outcome(item, False, f"status={state['status']}", state, trace_path)
    # The final step's result answers the question (earlier steps are intermediate).
    passed, reason = compare_results(state["results"][-1]["rows"], reference)
    return Outcome(item, passed, reason, state, trace_path)


def write_report(outcomes: list[Outcome], model: str, path: Path = REPORT_PATH) -> None:
    score = sum(o.passed for o in outcomes)
    lines = [
        "# Eval report",
        "",
        f"Generated by `python -m src.eval` on {datetime.now():%Y-%m-%d %H:%M}, "
        f"model `{model}`.",
        "",
        f"**Score: {score}/{len(outcomes)}**",
        "",
        "## How results are compared",
        "",
        "The agent's result (its final step) is compared with the result of a hand-written",
        "reference query (src/eval/questions.py), not the SQL text (src/eval/compare.py):",
        "",
        "- numbers are rounded to 2 decimals, strings are stripped;",
        "- column names and order are ignored, and the agent may return extra columns: we",
        "  try every way to pick agent columns for the reference columns;",
        "- row order is ignored and rows are compared as sets;",
        "- an empty reference needs an empty agent result (no rows, or one all-NULL row);",
        "- a run that does not end with status `done` (give_up, decline) fails.",
        "",
        "Limits: values must match exactly after rounding, so a course given by title where",
        "the reference has its code fails. Failures are read in their trace before calling",
        "them agent bugs.",
        "",
        "## Changes to the eval set",
        "",
        "The first run scored 6/10. Reading the 4 failures showed that 3 were reference",
        "mistakes, not agent mistakes (the agent's answers were right), so those references",
        "were changed:",
        "",
        "- #1: the reference returned only `COUNT(...)` = 11; the agent listed the 11 students",
        "  and the answer counted them. The reference now returns the failing students' ids.",
        "- #3, #4: the references used the course code, the agent used the course title (its",
        "  readable name). The references now use the title.",
        "",
        "#6 stayed a real fail in that run: the agent returned student, course code and",
        "semester but not the grade the question asks for.",
        "",
        "## Results",
        "",
        "| # | Pass | Covers | Question | Reason |",
        "|---|---|---|---|---|",
        *(f"| {o.item.id} | {'PASS' if o.passed else 'FAIL'} | {o.item.covers} | "
          f"{o.item.question} | {o.reason} |" for o in outcomes),
    ]
    for o in (o for o in outcomes if not o.passed):
        lines += _failure_section(o)
    path.write_text("\n".join(lines) + "\n")


def _failure_section(o: Outcome) -> list[str]:
    lines = ["", f"## Failed: #{o.item.id} {o.item.question}", "",
             f"Reason: {o.reason}. Status: `{o.state['status']}`. "
             f"Trace: `{os.path.relpath(o.trace_path, REPO_ROOT)}`", ""]
    for r in o.state["results"]:
        lines += [f"Agent step {r['step_index'] + 1}: {r['step']}", "",
                  "```sql", r["sql"], "```", "",
                  format_rows_as_table(r["columns"], r["rows"][:ROWS_IN_REPORT]), ""]
    lines += ["Agent answer:", "", "> " + o.state["answer"].replace("\n", "\n> "), "",
              "Reference SQL:", "", "```sql", o.item.sql.strip(), "```"]
    return lines


def main() -> None:
    load_dotenv()
    settings = load_settings()
    engine = connect_readonly(settings.database_url)
    model = os.getenv("OPENAI_MODEL")
    graph = build_graph(get_llm(), engine, settings.notes_path.read_text())

    outcomes = []
    for item in QUESTIONS:
        outcome = evaluate(item, graph, engine, model)
        print(f"{'PASS' if outcome.passed else 'FAIL'}  #{item.id:<2} {item.question}"
              f"\n        {outcome.reason}")
        outcomes.append(outcome)

    failed = [o for o in outcomes if not o.passed]
    print(f"\nScore: {len(outcomes) - len(failed)}/{len(outcomes)}")
    for o in failed:
        print(f"  failed #{o.item.id}: {o.item.question} ({o.reason})")
    write_report(outcomes, model)
    print(f"\nReport: {os.path.relpath(REPORT_PATH)}")


if __name__ == "__main__":
    main()
